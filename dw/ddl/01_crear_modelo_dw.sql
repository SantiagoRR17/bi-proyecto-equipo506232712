-- =============================================================================
-- 01_crear_modelo_dw.sql
-- Modelo dimensional (constelación de hechos) del Observatorio Distrital.
-- Motor: PostgreSQL 16 · Base de datos: observatorio_bi · Esquemas: dw, stg
--
-- Crea 5 dimensiones y 3 tablas de hechos, siguiendo el diagrama de la
-- Entrega 1 (Anexo B). Es re-ejecutable: borra y recrea el esquema dw.
-- ATENCIÓN: si dw ya tiene datos cargados, se pierden (el trabajo de PDI
-- los vuelve a generar desde las fuentes).
--
-- Convenciones
--   * Llaves de dimensión: sk_* (subrogada, entero). Las llaves de la fuente
--     se conservan como atributo (cod_localidad, cod_subcategoria, ...).
--   * Dimensiones generadas por la carga: IDENTITY "BY DEFAULT", de modo que
--     PDI puede insertar la llave que calcula (max + 1) o dejar que la genere
--     la base. Cada dimensión tiene un miembro -1 «DESCONOCIDO» (ver script 02)
--     para los registros sin coincidencia en el lookup.
--   * dim_tiempo usa la llave AAAAMMDD (p. ej. 20260715): es determinista, el
--     ETL la calcula desde la fecha y no necesita lookup.
--   * Nombres en minúscula (PostgreSQL pliega a minúscula los identificadores).
-- =============================================================================

BEGIN;

DROP SCHEMA IF EXISTS dw CASCADE;
CREATE SCHEMA dw;
COMMENT ON SCHEMA dw IS 'Almacén de datos dimensional (dimensiones y hechos)';

-- Esquema de paso (staging). Las tablas stg.* las define el ETL cuando se
-- diseñen las transformaciones; aquí solo se garantiza que el esquema exista.
CREATE SCHEMA IF NOT EXISTS stg;
COMMENT ON SCHEMA stg IS 'Área de paso (staging) del ETL';


-- =============================================================================
-- DIMENSIONES
-- =============================================================================

-- ---- DIM_TIEMPO -------------------------------------------------------------
-- Jerarquía: Día → Mes → Trimestre → Año. Una fila por día calendario.
CREATE TABLE dw.dim_tiempo (
    sk_tiempo   INTEGER      NOT NULL,   -- AAAAMMDD
    fecha       DATE         NOT NULL,
    dia         SMALLINT     NOT NULL,   -- día del mes (1-31)
    mes         VARCHAR(10)  NOT NULL,   -- nombre del mes ('Septiembre' es el más largo)
    numero_mes  SMALLINT     NOT NULL,   -- 1-12 (sirve para ordenar 'mes')
    trimestre   SMALLINT     NOT NULL,   -- 1-4
    anio        SMALLINT     NOT NULL,
    CONSTRAINT pk_dim_tiempo        PRIMARY KEY (sk_tiempo),
    CONSTRAINT uq_dim_tiempo_fecha  UNIQUE (fecha),
    CONSTRAINT ck_dim_tiempo_dia        CHECK (dia        BETWEEN 1 AND 31),
    CONSTRAINT ck_dim_tiempo_numero_mes CHECK (numero_mes BETWEEN 1 AND 12),
    CONSTRAINT ck_dim_tiempo_trimestre  CHECK (trimestre  BETWEEN 1 AND 4),
    CONSTRAINT ck_dim_tiempo_sk CHECK (
        sk_tiempo = EXTRACT(YEAR  FROM fecha)::int * 10000
                  + EXTRACT(MONTH FROM fecha)::int * 100
                  + EXTRACT(DAY   FROM fecha)::int
    )
);
COMMENT ON TABLE  dw.dim_tiempo IS 'Dimensión de tiempo (grano: un día). Jerarquía Día→Mes→Trimestre→Año';
COMMENT ON COLUMN dw.dim_tiempo.sk_tiempo IS 'Llave subrogada con formato AAAAMMDD';

-- ---- DIM_LOCALIDAD ----------------------------------------------------------
-- Jerarquía: Bogotá → Localidad. Fuente: F4 (geografia.json) + miembro -1.
CREATE TABLE dw.dim_localidad (
    sk_localidad         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cod_localidad        CHAR(2)       NOT NULL,   -- LocCodigo oficial, dos dígitos ('03')
    nombre_localidad     VARCHAR(50)   NOT NULL,
    acto_administrativo  VARCHAR(60),              -- LocAAdmini (máx. 36 caracteres en la fuente)
    area                 NUMERIC(15,2),            -- metros cuadrados (Sumapaz ≈ 7,8e8)
    CONSTRAINT pk_dim_localidad          PRIMARY KEY (sk_localidad),
    CONSTRAINT uq_dim_localidad_cod      UNIQUE (cod_localidad),
    CONSTRAINT uq_dim_localidad_nombre   UNIQUE (nombre_localidad),
    CONSTRAINT ck_dim_localidad_cod      CHECK (cod_localidad ~ '^[0-9]{2}$'),  -- rechaza "3" sin cero
    CONSTRAINT ck_dim_localidad_area     CHECK (area IS NULL OR area > 0)
);
COMMENT ON TABLE  dw.dim_localidad IS 'Dimensión conformada de localidad (20 oficiales + miembro -1 «SIN LOCALIDAD»)';
COMMENT ON COLUMN dw.dim_localidad.cod_localidad IS 'Código oficial de 2 caracteres; llave natural para relacionar F1, F2 y F3';
COMMENT ON COLUMN dw.dim_localidad.area IS 'Área en metros cuadrados (campo LocArea de F4)';

-- ---- DIM_TIPO_ALOJAMIENTO ---------------------------------------------------
-- Solo el código SUBCATRNT es verificable; la etiqueta se asigna únicamente si
-- se confirma con el diccionario (por eso admite NULL).
CREATE TABLE dw.dim_tipo_alojamiento (
    sk_tipo_alojamiento  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cod_subcategoria     VARCHAR(10)   NOT NULL,   -- SUBCATRNT como texto ('6' a '12')
    etiqueta             VARCHAR(100),             -- por verificar contra el diccionario
    CONSTRAINT pk_dim_tipo_alojamiento      PRIMARY KEY (sk_tipo_alojamiento),
    CONSTRAINT uq_dim_tipo_alojamiento_cod  UNIQUE (cod_subcategoria)
);
COMMENT ON TABLE  dw.dim_tipo_alojamiento IS 'Subcategoría RNT del alojamiento (F1). Etiqueta pendiente de verificar';
COMMENT ON COLUMN dw.dim_tipo_alojamiento.etiqueta IS 'POR VERIFICAR: el diccionario usa letras A-Z y el dato usa códigos numéricos; no se asigna sin certeza';

-- ---- DIM_TIPO_HURTO ---------------------------------------------------------
-- Jerarquía: Artículo → Tipo de hurto. Fuente: F2, campo TIPO DE HURTO.
CREATE TABLE dw.dim_tipo_hurto (
    sk_tipo_hurto      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    etiqueta_original  VARCHAR(100)  NOT NULL,   -- texto completo de la fuente (máx. 41)
    articulo           VARCHAR(30)   NOT NULL,   -- p. ej. 'ARTÍCULO 239'
    descripcion_tipo   VARCHAR(100)  NOT NULL,   -- p. ej. 'HURTO RESIDENCIAS'
    CONSTRAINT pk_dim_tipo_hurto           PRIMARY KEY (sk_tipo_hurto),
    CONSTRAINT uq_dim_tipo_hurto_etiqueta  UNIQUE (etiqueta_original)
);
COMMENT ON TABLE dw.dim_tipo_hurto IS 'Tipo de hurto según la clasificación de la fuente policial (F2)';

-- ---- DIM_CARACTERISTICA_HURTO -----------------------------------------------
-- Combinaciones de arma/medio, género y grupo etario. Los vacíos de la fuente
-- se representan como 'SIN DATO' (no se suponen categorías).
CREATE TABLE dw.dim_caracteristica_hurto (
    sk_caracteristica  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    arma_medio         VARCHAR(40)  NOT NULL,   -- ARMAS MEDIOS (máx. 27)
    genero             VARCHAR(20)  NOT NULL,   -- GENERO (máx. 10) o 'SIN DATO'
    grupo_etario       VARCHAR(20)  NOT NULL,   -- GRUPO ETARIO (máx. 12) o 'SIN DATO'
    CONSTRAINT pk_dim_caracteristica_hurto  PRIMARY KEY (sk_caracteristica),
    CONSTRAINT uq_dim_caracteristica_hurto  UNIQUE (arma_medio, genero, grupo_etario)
);
COMMENT ON TABLE dw.dim_caracteristica_hurto IS 'Combinación arma/medio × género × grupo etario (68 combinaciones reales en Bogotá)';


-- =============================================================================
-- TABLAS DE HECHOS
-- =============================================================================

-- ---- FACT_DINAMICA_EMPRESARIAL ----------------------------------------------
-- Grano: una localidad en un corte de medición (sep-2023, mar-2024, jul-2025).
CREATE TABLE dw.fact_dinamica_empresarial (
    sk_localidad                    INTEGER       NOT NULL,
    sk_tiempo                       INTEGER       NOT NULL,   -- fecha del corte
    empresas_vigentes               INTEGER       NOT NULL,
    establecimientos_vigentes       INTEGER,                  -- NULL en el corte de 2023 (no disponible)
    variacion_empresas_pct          NUMERIC(9,4),             -- NULL en el primer corte
    variacion_establecimientos_pct  NUMERIC(9,4),             -- NULL en 2023 y en 2024 (sin periodo anterior)
    CONSTRAINT pk_fact_dinamica_empresarial PRIMARY KEY (sk_localidad, sk_tiempo),
    CONSTRAINT fk_fact_dinamica_localidad FOREIGN KEY (sk_localidad) REFERENCES dw.dim_localidad (sk_localidad),
    CONSTRAINT fk_fact_dinamica_tiempo    FOREIGN KEY (sk_tiempo)    REFERENCES dw.dim_tiempo (sk_tiempo),
    CONSTRAINT ck_fact_dinamica_empresas       CHECK (empresas_vigentes >= 0),
    CONSTRAINT ck_fact_dinamica_establecim     CHECK (establecimientos_vigentes IS NULL OR establecimientos_vigentes >= 0)
);
COMMENT ON TABLE  dw.fact_dinamica_empresarial IS 'Grano: una localidad en un corte de medición de la dinámica empresarial';
COMMENT ON COLUMN dw.fact_dinamica_empresarial.variacion_empresas_pct IS 'Métrica NO aditiva: (actual − anterior) / anterior × 100. Los cortes están separados por 6 y 16 meses';
CREATE INDEX ix_fact_dinamica_tiempo ON dw.fact_dinamica_empresarial (sk_tiempo);

-- ---- FACT_ALOJAMIENTO -------------------------------------------------------
-- Grano: un establecimiento (reg_rnt) en la fecha de corte de la fuente.
CREATE TABLE dw.fact_alojamiento (
    reg_rnt               INTEGER      NOT NULL,   -- REGNTURISM; dimensión degenerada (396 a 250532)
    sk_localidad          INTEGER      NOT NULL,
    sk_tiempo             INTEGER      NOT NULL,   -- fecha de corte (descarga: 2026-10-22)
    sk_tipo_alojamiento   INTEGER      NOT NULL,
    cantidad_alojamientos INTEGER      NOT NULL DEFAULT 1,
    participacion_pct     NUMERIC(7,4),            -- 0 a 100,0000
    CONSTRAINT pk_fact_alojamiento PRIMARY KEY (reg_rnt),
    CONSTRAINT fk_fact_alojamiento_localidad FOREIGN KEY (sk_localidad)        REFERENCES dw.dim_localidad (sk_localidad),
    CONSTRAINT fk_fact_alojamiento_tiempo    FOREIGN KEY (sk_tiempo)           REFERENCES dw.dim_tiempo (sk_tiempo),
    CONSTRAINT fk_fact_alojamiento_tipo      FOREIGN KEY (sk_tipo_alojamiento) REFERENCES dw.dim_tipo_alojamiento (sk_tipo_alojamiento),
    CONSTRAINT ck_fact_alojamiento_cantidad      CHECK (cantidad_alojamientos = 1),   -- una fila = un establecimiento
    CONSTRAINT ck_fact_alojamiento_participacion CHECK (participacion_pct IS NULL OR participacion_pct BETWEEN 0 AND 100)
);
COMMENT ON TABLE  dw.fact_alojamiento IS 'Grano: un establecimiento de alojamiento (reg_rnt) en la fecha de corte de la fuente';
COMMENT ON COLUMN dw.fact_alojamiento.participacion_pct IS 'Métrica NO aditiva: alojamientos de la localidad / alojamientos de Bogotá × 100. Se repite en cada fila de la localidad: NO sumar, usar AVG o recalcular';
CREATE INDEX ix_fact_alojamiento_localidad ON dw.fact_alojamiento (sk_localidad);
CREATE INDEX ix_fact_alojamiento_tiempo    ON dw.fact_alojamiento (sk_tiempo);
CREATE INDEX ix_fact_alojamiento_tipo      ON dw.fact_alojamiento (sk_tipo_alojamiento);

-- ---- FACT_HURTOS ------------------------------------------------------------
-- Grano: un registro de la fuente policial ocurrido en Bogotá D.C.
-- No se agrupan ni se eliminan filas; nro_fila_fuente da la trazabilidad al CSV.
CREATE TABLE dw.fact_hurtos (
    nro_fila_fuente     INTEGER  NOT NULL,   -- número de fila en el CSV original; dimensión degenerada
    sk_tiempo           INTEGER  NOT NULL,   -- FECHA HECHO
    sk_localidad        INTEGER  NOT NULL,
    sk_tipo_hurto       INTEGER  NOT NULL,
    sk_caracteristica   INTEGER  NOT NULL,
    cantidad_reportada  INTEGER  NOT NULL,   -- CANTIDAD (vale 1 en todas las filas)
    CONSTRAINT pk_fact_hurtos PRIMARY KEY (nro_fila_fuente),
    CONSTRAINT fk_fact_hurtos_tiempo         FOREIGN KEY (sk_tiempo)         REFERENCES dw.dim_tiempo (sk_tiempo),
    CONSTRAINT fk_fact_hurtos_localidad      FOREIGN KEY (sk_localidad)      REFERENCES dw.dim_localidad (sk_localidad),
    CONSTRAINT fk_fact_hurtos_tipo           FOREIGN KEY (sk_tipo_hurto)     REFERENCES dw.dim_tipo_hurto (sk_tipo_hurto),
    CONSTRAINT fk_fact_hurtos_caracteristica FOREIGN KEY (sk_caracteristica) REFERENCES dw.dim_caracteristica_hurto (sk_caracteristica),
    CONSTRAINT ck_fact_hurtos_cantidad CHECK (cantidad_reportada > 0)
);
COMMENT ON TABLE  dw.fact_hurtos IS 'Grano: un registro de la fuente policial (Bogotá D.C.). COUNT(*) = número de registros; SUM(cantidad_reportada) = cantidad reportada';
COMMENT ON COLUMN dw.fact_hurtos.nro_fila_fuente IS 'Número de fila del CSV original (trazabilidad). Dimensión degenerada';
CREATE INDEX ix_fact_hurtos_tiempo         ON dw.fact_hurtos (sk_tiempo);
CREATE INDEX ix_fact_hurtos_localidad      ON dw.fact_hurtos (sk_localidad);
CREATE INDEX ix_fact_hurtos_tipo           ON dw.fact_hurtos (sk_tipo_hurto);
CREATE INDEX ix_fact_hurtos_caracteristica ON dw.fact_hurtos (sk_caracteristica);

COMMIT;

